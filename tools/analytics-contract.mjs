import {readFile,writeFile} from 'node:fs/promises';
// The JSON remains the one source shared with native. Compile-time sender types
// are generated and checked, so stale/extra/wrong-type fields fail npm run check.
const contract=JSON.parse(await readFile('src/platform/analytics-contract.json','utf8'));
for(const [event,fields] of Object.entries(contract)){
  if(!/^[a-z][a-z0-9_]+$/.test(event)||!fields||typeof fields!=='object'||Array.isArray(fields))throw Error('Invalid analytics schema');
  for(const [key,type]of Object.entries(fields))if(!/^[a-z][a-z0-9_]+$/.test(key)||!['string','boolean','number'].includes(type))throw Error('Invalid analytics field');
}
const source='// Generated by tools/analytics-contract.mjs from analytics-contract.json. Do not edit.\nexport interface AnalyticsPayloads {\n'+Object.entries(contract).map(([event,fields])=>'  '+event+': { '+Object.entries(fields).map(([key,type])=>key+': '+type).join('; ')+' };').join('\n')+'\n}\n';
const path='src/platform/analytics-schema.d.ts';
if(process.argv.includes('--write'))await writeFile(path,source);
else if(await readFile(path,'utf8')!==source)throw Error('Analytics types are stale: run npm run analytics:generate');
console.info(`Analytics contract: ${Object.keys(contract).length} exact event schemas; generated sender types match native source.`);
